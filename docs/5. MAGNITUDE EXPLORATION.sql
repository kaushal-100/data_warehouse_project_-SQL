--5. MAGNITUDE EXPLORATION

--Find Total Customers by Countries
SELECT
	Country,
	COUNT(Customer_key) AS [Total Customers]
FROM gold.dim_customers
GROUP BY Country
ORDER BY [Total Customers] DESC

--Find Total Customers by Gender
SELECT
	Gender,
	COUNT(Customer_key) AS [Total Customers]
FROM gold.dim_customers
GROUP BY Gender
ORDER BY [Total Customers] DESC
--Find Total Products by Categories
SELECT
	Category,
	COUNT(Product_Key) AS [Total Products]
FROM gold.dim_products
GROUP BY Category
ORDER BY [Total Products] DESC

--What is the average costs in each category ?
SELECT
	Category,
	AVG(Product_Cost) AS [Average Cost]
FROM gold.dim_products
GROUP BY Category
ORDER BY [Average Cost] DESC
--What is the total revenue generated for each category ?
SELECT
	p.Category,
	SUM(f.[Sales Amount]) AS [Total Revenue]
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON f.Product_Key = p.Product_Key
GROUP BY p.Category
ORDER BY [Total Revenue] DESC

--Find Total revenue which is generated by each customer
SELECT
	c.Customer_key,
	c.First_Name,
	c.Last_Name,
	SUM(f.[Sales Amount]) AS [Total Sales Made]
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON f.Customer_key = c.Customer_key
GROUP BY c.Customer_key, c.First_Name, c.Last_Name
ORDER BY [Total Sales Made] DESC

--What is the distribution of sold items across countries ?
SELECT
	c.Country,
	SUM(f.Quantity) AS [Total Items Sold]
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON f.Customer_key = c.Customer_key
GROUP BY c.Country
ORDER BY [Total Items Sold] DESC